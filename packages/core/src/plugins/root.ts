import type { ResolvedOptions } from '../types'
import { existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { slash } from '@antfu/utils'
import UniKuRoot from '@uni-ku/root'
import { ROOT_NAME } from '../constant'
import { log } from '../utils/logger'

/** 虚拟根组件最小模板 */
const APP_KU_VUE_TEMPLATE = `<!-- Auto-generated by @univa/core -->
<template>
  <KuRootView />
</template>
`

function ensureRootComponent(fileName: string, srcDirAbs: string) {
  const rootComponentPath = join(srcDirAbs, `${fileName}.vue`)

  if (existsSync(rootComponentPath)) {
    return
  }

  writeFileSync(rootComponentPath, APP_KU_VUE_TEMPLATE, 'utf-8')

  log(`已生成虚拟根组件：${slash(rootComponentPath)}`)
}

/**
 * 创建 Root 模块插件
 *
 * 确保虚拟根组件存在后创建 @uni-ku/root 插件。
 */
export function createRootPlugin(resolved: ResolvedOptions) {
  const rootFileName = resolved.overrides.root?.rootFileName ?? ROOT_NAME

  ensureRootComponent(rootFileName, resolved.srcDirAbs)

  return UniKuRoot({
    enabledVirtualHost: true,
    enabledGlobalRef: true,
    rootFileName,
    excludePages: [
      `${resolved.dirs.componentsAsyncDir}/**/*.*`,
    ],
    ...resolved.overrides.root,
  })
}
