import type { ResolvedOptions } from '../types'
import { existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { slash } from '@antfu/utils'
import UniKuRoot from '@uni-ku/root'
import { COMPONENTS_ASYNC_DIR_NAME, ROOT_NAME } from '../constant'
import { log } from '../utils/logger'

/** 虚拟根组件最小模板 */
const APP_KU_VUE_TEMPLATE = `<!-- Auto-generated by @univa/core -->
<template>
  <KuRootView />
</template>
`

function ensureRootComponent(fileName: string, srcDirAbs: string) {
  const rootComponentPath = join(srcDirAbs, fileName)

  if (existsSync(rootComponentPath)) {
    return
  }

  writeFileSync(rootComponentPath, APP_KU_VUE_TEMPLATE, 'utf-8')

  log(`已生成虚拟根组件：${slash(rootComponentPath)}`)
}

export function createRootPlugin(options: ResolvedOptions) {
  let rootFileName = `${ROOT_NAME}.vue`
  if (options.overrides?.root?.rootFileName) {
    rootFileName = `${options.overrides.root.rootFileName}.vue`
  }
  ensureRootComponent(rootFileName, options.srcDirAbs)
  return UniKuRoot({
    enabledVirtualHost: true,
    enabledGlobalRef: true,
    rootFileName: ROOT_NAME,
    excludePages: [
      `${COMPONENTS_ASYNC_DIR_NAME}/**/*.*`,
    ],
    ...options.overrides?.root,
  })
}
