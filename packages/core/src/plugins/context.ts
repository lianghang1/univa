import type { ViteDevServer } from 'vite'
import type { UnivaOptions } from '../types'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { slash } from '@antfu/utils'
import { loadConfig } from 'c12'
import { createJiti } from 'jiti'
import { ID } from '../constant'
import { log } from '../utils/logger'
import { mergeWithArrayOverride } from '../utils/merge'
import { generatePagesConfigFile, getPagesConfigPath } from './pages'

/** 默认虚拟根组件文件名（UniKuRoot 约定） */
const DEFAULT_ROOT_FILE_NAME = 'App.ku.vue'

/** 虚拟根组件最小模板 */
const APP_KU_VUE_TEMPLATE = `<!-- Auto-generated by @univa/core -->
<!-- UniKuRoot 虚拟根组件，可在此添加全局组件（如 Toast、ConfigProvider 等） -->
<template>
  <KuRootView />
</template>
`

/**
 * Univa Context 类
 * 负责管理配置、监听文件变化、触发生成函数
 */
export class UnivaContext {
  private _server: ViteDevServer | undefined

  config?: UnivaOptions
  configPath?: string
  root: string

  constructor(options: { root: string }) {
    this.root = options.root
  }

  /**
   * 确保虚拟根组件文件存在
   *
   * UniKuRoot 插件依赖 src 下的虚拟根组件文件（默认 App.ku.vue）。
   * 若不存在则生成最小模板，避免插件注入 import 时解析失败。
   *
   * 必须在 Vite 启动前调用（Univa() 初始化阶段），
   * 否则在 configResolved 阶段创建 src 下新文件会触发 watcher add 事件，
   * 导致 Vite 重编译与 VitePluginUniPages 的 pages.json 写入冲突（EPERM）。
   */
  ensureRootComponent() {
    const srcDir = this.config?.srcDir || 'src'
    const rootFileName = this.config?.overrides?.root?.rootFileName || DEFAULT_ROOT_FILE_NAME
    const rootComponentPath = join(this.root, srcDir, rootFileName)

    if (existsSync(rootComponentPath)) {
      return
    }

    writeFileSync(rootComponentPath, APP_KU_VUE_TEMPLATE, 'utf-8')

    log(`已生成虚拟根组件：${slash(rootComponentPath)}`)
  }

  /**
   * 同步加载用户配置（univa.config.ts）
   */
  loadUserConfigSync() {
    const jiti = createJiti(this.root)
    const configFile = join(this.root, `${ID}.config`)

    try {
      const configModule = jiti(configFile)
      const userConfig = configModule?.default || configModule

      this.config = mergeWithArrayOverride({}, userConfig)
      this.configPath = jiti.resolve(configFile)
    }
    catch {
      // 配置文件不存在，使用默认配置
    }
  }

  /**
   * 异步加载用户配置（c12 支持更多格式与合并能力）
   */
  async loadUserConfigAsync() {
    const { config: userConfig, configFile } = await loadConfig<UnivaOptions>({
      name: ID,
      cwd: this.root,
      defaults: this.config || {},
      merger: mergeWithArrayOverride as any,
    })

    this.config = userConfig
    this.configPath = configFile || ''
  }

  /**
   * 设置 Vite 开发服务器
   */
  setupViteServer(server: ViteDevServer) {
    if (this._server === server)
      return

    this._server = server
    this.setupWatcher(server.watcher)
  }

  /**
   * 设置文件监听器
   *
   * 监听 univa.config.ts 变化，重新生成 .univa/pages.ts
   */
  setupWatcher(watcher: ViteDevServer['watcher']) {
    if (!this.configPath) {
      return
    }

    watcher.add(this.configPath)

    watcher.on('change', async (filePath) => {
      filePath = slash(filePath)
      const configPath = slash(this.configPath || '')

      if (filePath !== configPath) {
        return
      }

      await this.updateConfig()
      this.onUpdate()
    })
  }

  async updateConfig() {
    await this.loadUserConfigAsync()
    this.updateGeneratedFiles()
  }

  /**
   * 更新生成的文件
   *
   * 读取 univa.config.ts 的 pages 字段（应用级配置），
   * 生成 .univa/pages-config.ts 供 VitePluginUniPages 消费。
   *
   * 注意：不在此处生成 src/App.ku.vue，避免在 configResolved 阶段
   * 创建 src 下新文件触发 watcher add 事件，导致 Vite 重编译
   * 与 VitePluginUniPages 的 pages.json 写入冲突（EPERM）。
   * App.ku.vue 的生成在 Univa() 初始化阶段完成。
   */
  updateGeneratedFiles() {
    const pagesConfig = this.config?.pages
    if (pagesConfig) {
      generatePagesConfigFile(pagesConfig, this.root)
    }

    // 若 pages 字段不存在，确保 .univa/pages-config.ts 至少存在空配置
    const pagesTsPath = getPagesConfigPath(this.root)
    const emptyContent = `// Auto-generated by @univa/core\nexport default {}\n`
    if (!existsSync(pagesTsPath)) {
      writeFileSync(pagesTsPath, emptyContent, 'utf-8')
    }
    else if (!pagesConfig) {
      if (readFileSync(pagesTsPath, 'utf-8') !== emptyContent) {
        writeFileSync(pagesTsPath, emptyContent, 'utf-8')
      }
    }
  }

  /**
   * 更新回调
   * 触发 HMR
   */
  onUpdate() {
    if (!this._server) {
      return
    }

    this._server.ws.send({
      type: 'full-reload',
    })
  }
}
