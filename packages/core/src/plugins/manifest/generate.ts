import type { UserManifestConfig } from '@uni-helper/vite-plugin-uni-manifest'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { getUnivaDir } from '../../utils/fs'
import { log } from '../../utils/logger'

/** 获取 .univa/manifest.config.ts 绝对路径 */
export function getManifestConfigPath(root: string): string {
  return join(getUnivaDir(root), 'manifest.config.ts')
}

/**
 * 生成 .univa/manifest.config.ts 文件内容
 *
 * 将 univa.config.ts 的 manifest 字段（应用级配置）序列化为 TypeScript 模块，
 * 供 VitePluginUniManifest（c12 watchConfig）消费。
 */
function generateManifestConfigContent(content: Partial<UserManifestConfig> = {}): string {
  return `/* eslint-disable */
/* prettier-ignore */
// @ts-nocheck
// Auto-generated by @univa/core
export default ${JSON.stringify(content, null, 2)}
`
}

/**
 * 生成 .univa/manifest.config.ts 文件
 *
 * 仅在内容变化时写入，避免触发不必要的 Vite 重编译。
 */
export function generateManifestConfigFile(content: Partial<UserManifestConfig> = {}, root: string): void {
  const configPath = getManifestConfigPath(root)
  const newContent = generateManifestConfigContent(content)

  if (existsSync(configPath)) {
    const existingContent = readFileSync(configPath, 'utf-8')
    if (existingContent === newContent) {
      return
    }
  }

  writeFileSync(configPath, newContent, 'utf-8')
  log(`Generated manifest config file: ${configPath}`)
}
