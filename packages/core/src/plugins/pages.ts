import type { PagesConfig } from '@uni-helper/uni-pages-types'
import type { UserOptions as PagesPluginOptions } from '@uni-helper/vite-plugin-uni-pages'
import type { Plugin } from 'vite'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { VitePluginUniPages } from '@uni-helper/vite-plugin-uni-pages'
import { getUnivaDir } from '../utils/fs'

/**
 * 获取 .univa/pages.ts 文件路径（VitePluginUniPages 的 configSource）
 */
export function getPagesConfigPath(cwd: string): string {
  const univaDir = getUnivaDir(cwd)
  return join(univaDir, 'pages-config.ts')
}

/**
 * 生成 .univa/pages.ts 文件内容
 *
 * 将用户通过 definePagesConfig 声明的应用级配置（globalStyle/tabBar 等）
 * 序列化为 TypeScript 模块，供 VitePluginUniPages 消费。
 *
 * pages/subPackages 字段由 VitePluginUniPages 扫描目录后自动填充，
 * 此处不写入，避免覆盖扫描结果。
 */
function generatePagesConfigContent(content: Partial<PagesConfig>): string {
  // 移除 pages/subPackages，由扫描结果填充
  const { pages, subPackages, ...rest } = content
  void pages
  void subPackages
  return `// Auto-generated by @univa/core
// 来源：definePagesConfig() 声明的应用级配置
export default ${JSON.stringify(rest, null, 2)}
`
}

/**
 * 生成 .univa/pages.ts 文件
 *
 * 仅在内容变化时写入，避免触发不必要的 Vite 重编译。
 */
export function generatePagesConfigFile(content: Partial<PagesConfig>, cwd: string): void {
  const pagesConfigPath = getPagesConfigPath(cwd)
  const newContent = generatePagesConfigContent(content)

  if (existsSync(pagesConfigPath)) {
    const existingContent = readFileSync(pagesConfigPath, 'utf-8')
    if (existingContent === newContent) {
      return
    }
  }

  writeFileSync(pagesConfigPath, newContent, 'utf-8')
}

/**
 * 创建 Pages 模块插件
 *
 * 职责：
 * 1. 创建 VitePluginUniPages，configSource 指向 .univa/pages.ts
 * 2. dts 输出到 .univa 目录
 * 3. 高层约定（dirs.pages）已在外部解析为绝对路径传入
 */
export function createPagesPlugin(pluginOptions: PagesPluginOptions, cwd: string): Plugin[] {
  const univaDir = getUnivaDir(cwd)

  const result = VitePluginUniPages({
    dts: `${univaDir}/uni-pages.d.ts`,
    exclude: ['**/components/**/*.*'],
    configSource: getPagesConfigPath(cwd),
    ...pluginOptions,
  })

  return Array.isArray(result) ? result : [result]
}
