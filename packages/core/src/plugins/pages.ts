import type { PagesConfig } from '@uni-helper/uni-pages-types'
import type { UserOptions as PagesPluginOptions } from '@uni-helper/vite-plugin-uni-pages'
import type { Plugin } from 'vite'
import type { PagesOptions } from '../types'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { VitePluginUniPages } from '@uni-helper/vite-plugin-uni-pages'
import { getUnivaDir } from '../utils/fs'

const PAGES_JSON_KEYS: (keyof PagesConfig)[] = [
  'globalStyle',
  'tabBar',
  'easycom',
  'condition',
]

export function hasPagesJsonContent(config: unknown): boolean {
  if (!config || typeof config !== 'object' || Array.isArray(config))
    return false
  const c = config as Record<string, unknown>
  return PAGES_JSON_KEYS.some(key => key in c) || 'content' in c
}

export function extractPagesJsonContent(config: PagesOptions | PagesPluginOptions): PagesConfig | undefined {
  if (!config || typeof config !== 'object')
    return undefined

  const content: Partial<PagesConfig> = {}

  for (const key of PAGES_JSON_KEYS) {
    if (key in config) {
      content[key] = (config as Record<string, unknown>)[key]
    }
  }

  if ('content' in config && config.content) {
    for (const key of PAGES_JSON_KEYS) {
      if (key in config.content) {
        content[key] = (config.content as Record<string, unknown>)[key]
      }
    }
  }

  return Object.keys(content).length > 0 ? content : undefined
}

export function extractPluginOptions(config: PagesOptions | PagesPluginOptions): PagesPluginOptions {
  if (!config || typeof config !== 'object')
    return {}

  const options: PagesPluginOptions = {}

  for (const key in config) {
    if (key !== 'content' && key !== 'options' && !PAGES_JSON_KEYS.includes(key as keyof PagesConfig)) {
      (options as Record<string, unknown>)[key] = (config as Record<string, unknown>)[key]
    }
  }

  if ('options' in config && config.options) {
    for (const key in config.options) {
      (options as Record<string, unknown>)[key] = (config.options as Record<string, unknown>)[key]
    }
  }

  return options
}

function generatePagesConfigContent(content: Partial<PagesConfig>): string {
  return `// Auto-generated by @univa/core
export default ${JSON.stringify(content, null, 2)}
`
}

/**
 * 获取文件路径
 */
function getPagesConfigPath(cwd: string): string {
  const univaDir = getUnivaDir(cwd)
  return join(univaDir, 'pages.config.ts')
}

export function generatePagesConfigFile(content: Partial<PagesConfig>, cwd: string): void {
  const pagesConfigPath = getPagesConfigPath(cwd)

  const newContent = generatePagesConfigContent(content)

  if (existsSync(pagesConfigPath)) {
    const existingContent = readFileSync(pagesConfigPath, 'utf-8')
    if (existingContent === newContent) {
      return
    }
  }

  writeFileSync(pagesConfigPath, newContent, 'utf-8')
}

export function createPagesPlugin(config: PagesOptions | PagesPluginOptions | true, cwd: string): Plugin[] {
  const pagesConfig = config === true ? {} : config

  if (pagesConfig && hasPagesJsonContent(pagesConfig)) {
    const jsonContent = extractPagesJsonContent(pagesConfig as PagesOptions)
    if (jsonContent) {
      generatePagesConfigFile(jsonContent, cwd)
    }

    const pluginOptions = extractPluginOptions(pagesConfig as PagesOptions)
    pluginOptions.configSource = getPagesConfigPath(cwd)

    const result = VitePluginUniPages(pluginOptions as any)
    return Array.isArray(result) ? result : [result]
  }

  const result = VitePluginUniPages(pagesConfig as any)
  return Array.isArray(result) ? result : [result]
}
